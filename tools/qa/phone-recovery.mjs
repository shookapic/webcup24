// Physical phone recovery switch: visible control -> flat accessible dialog, remembered, reversible. node tools/qa/phone-recovery.mjs <base>
import puppeteer from 'puppeteer-core';
const [base] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: process.env.BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: 'new', protocolTimeout: 600000, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
await page.setViewport({ width: 1280, height: 800 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
let bad = 0;
const check = (name, ok, info = '') => { if (!ok) bad++; console.log(ok ? 'PASS' : 'FAIL', name, info); };
const settle = (ms = 900) => new Promise((r) => setTimeout(r, ms));
await page.goto(base + '/', { waitUntil: 'networkidle0' });
await page.evaluate(async () => {
  const post = (u, m, b) => fetch(u, { method: m, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(b) });
  await post('/api/auth/register', 'POST', { name: 'Probe', email: `p${Date.now()}${Math.random()}@example.org`, password: 'motdepasse-solide-123' });
  await post('/api/me/avatar', 'PUT', { skin: '#e0ac69', outfit: '#3a6ea5', accent: '#ff4fa3' });
  const { user } = await (await fetch('/api/me')).json();
  localStorage.setItem(`world-seen-alerts:${user.id}`, JSON.stringify(Array.from({ length: 200 }, (_, i) => i)));
  localStorage.removeItem('tn.flatphone');
});
await page.goto(`${base}/monde/?debug&fps=30`, { waitUntil: 'networkidle0' });
await page.waitForFunction(() => window.__tn?.run, { timeout: 60000 });
await page.evaluate(async () => { const tn = window.__tn; for (let i = 0; i < 60 && !tn.ecctrl; i++) await tn.run(0.5); await tn.run(1); });
await page.keyboard.press('KeyT'); await settle(1500);
check('T opens the physical phone (3D host) and shows the recovery control', (await page.$('.phone-host')) !== null && (await page.$('.recovery-top button')) !== null);
check('recovery control is a real, labelled button with a description', await page.$eval('.recovery-top button', (b) => b.textContent.includes('Version simple') && b.getAttribute('aria-describedby') === 'recovery-help'));
await page.screenshot({ path: 'docs/qa-captures/phone-recovery-1-physical.png' });
await page.click('.recovery-top button'); await settle(1200);
check('click switches to the flat accessible dialog: one dialog, no 3D host, one phone screen', (await page.$('.phone-sheet[role=dialog]')) !== null && (await page.$('.phone-host')) === null && (await page.$$eval('.phone-screen', (els) => els.length)) === 1);
check('preference remembered (localStorage tn.flatphone=1)', (await page.evaluate(() => localStorage.getItem('tn.flatphone'))) === '1');
await page.screenshot({ path: 'docs/qa-captures/phone-recovery-2-flat.png' });
await page.keyboard.press('Escape'); await settle(900);
check('Escape closes the flat dialog; the 3D-phone return control appears while the phone is closed', (await page.$('.phone-sheet')) === null && (await page.$('.recovery-bottom button')) !== null);
await page.reload({ waitUntil: 'networkidle0' });
await page.waitForFunction(() => window.__tn?.run, { timeout: 60000 });
await page.evaluate(async () => { const tn = window.__tn; for (let i = 0; i < 60 && !tn.ecctrl; i++) await tn.run(0.5); await tn.run(1); });
await page.keyboard.press('KeyT'); await settle(1500);
check('after a reload T opens the flat dialog directly (choice remembered)', (await page.$('.phone-sheet[role=dialog]')) !== null && (await page.$('.phone-host')) === null);
await page.keyboard.press('Escape'); await settle(900);
await page.click('.recovery-bottom button'); await settle(500);
check('return control clears the preference', (await page.evaluate(() => localStorage.getItem('tn.flatphone'))) === null && (await page.$('.recovery-bottom')) === null);
await page.keyboard.press('KeyT'); await settle(1500);
check('T opens the physical phone again', (await page.$('.phone-host')) !== null);
check('no page errors', errors.length === 0, errors.join(' | '));
await browser.close();
console.log(bad ? `FAILURES (${bad})` : 'ALL PASS');
process.exit(bad ? 1 : 0);
